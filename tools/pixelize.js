// One-time build step: turns each cut-out in images/objects into a small
// pixel sprite and writes js/artifact-sprites.js. Re-run after changing a
// photo:  node tools/pixelize.js   (add --preview to save a contact sheet)
const { spawn } = require("child_process");
const fs = require("fs");
const net = require("net");
const path = require("path");
const cdp = require("../tests/cdp.js");
const TourData = require("../js/tour-data.js");

const ROOT = path.resolve(__dirname, "..");

// For a piece with no openly licensed photo yet: a blank museum label on a
// little stand, so the case isn't empty and doesn't pretend to show it.
const PLACEHOLDER = {
  w: 14, h: 15, pal: ["#2a2230", "#efe6d0", "#9c8f7a", "#c9a24a"],
  px: [
    "..............",
    "..0000000000..",
    "..0111111110..",
    "..0122221110..",
    "..0111111110..",
    "..0122222210..",
    "..0111111110..",
    "..0122211110..",
    "..0111111110..",
    "..0000000000..",
    "......00......",
    "......00......",
    "....003300....",
    "...00333300...",
    "..............",
  ].join("")
};
const freePort = () => new Promise(res => { const s = net.createServer(); s.listen(0, "127.0.0.1", () => { const { port } = s.address(); s.close(() => res(port)); }); });

(async () => {
  const port = await freePort();
  const server = spawn("python3", ["-m", "http.server", String(port), "--bind", "127.0.0.1"], { cwd: ROOT, stdio: "ignore" });
  const base = `http://127.0.0.1:${port}/`;
  for (let i = 0; i < 60; i++) { try { if ((await fetch(base)).ok) break; } catch (e) { await cdp.sleep(100); } }
  const client = await cdp.launch();
  try {
    await client.send("Page.enable");
    await cdp.load(client, base + "tools/pixelize.html", null, { settle: false });
    const ids = TourData.fullTour().map(s => s[1]);
    const sprites = {};
    for (const id of ids) {
      sprites[id] = TourData.PIECES[id].photo ? await client.eval(`pixelize(${JSON.stringify(id)})`) : PLACEHOLDER;
    }
    const body = Object.entries(sprites).map(([id, s]) => `  ${JSON.stringify(id)}: ${JSON.stringify(s)}`).join(",\n");
    fs.writeFileSync(path.join(ROOT, "js/artifact-sprites.js"),
      "// Generated by tools/pixelize.js from images/objects. Do not edit by hand.\n" +
      "// px is the sprite row by row; each character indexes pal, '.' is transparent.\n" +
      "(function (root) {\n  const ARTIFACT_SPRITES = {\n" + body + "\n  };\n" +
      "  if (typeof module !== \"undefined\" && module.exports) module.exports = { ARTIFACT_SPRITES };\n" +
      "  else root.ARTIFACT_SPRITES = ARTIFACT_SPRITES;\n})(typeof globalThis !== \"undefined\" ? globalThis : this);\n");
    console.log(`wrote ${ids.length} sprites`);
    if (process.argv.includes("--preview")) {
      await client.send("Emulation.setDeviceMetricsOverride", { width: 1100, height: 900, deviceScaleFactor: 1, mobile: false });
      await client.eval(`preview(${JSON.stringify(sprites)})`);
      const shot = await client.send("Page.captureScreenshot", { format: "png" });
      const out = process.argv[process.argv.indexOf("--preview") + 1] || path.join(ROOT, "tools/preview.png");
      fs.writeFileSync(out, Buffer.from(shot.data, "base64"));
      console.log("preview:", out);
    }
  } finally {
    await client.close();
    server.kill();
  }
})().catch(e => { console.error(e); process.exit(1); });
