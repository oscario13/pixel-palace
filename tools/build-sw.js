// Writes sw.js: the list of every file the game needs, plus a version made
// from their contents, so the service worker can cache the whole game for
// offline use and pick up changes automatically. tests/run.js runs this
// first; run it yourself after editing any file: node tools/build-sw.js
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DIRS = ["css", "js", "js/pieces", "icons", "images/objects", "images/photos"];
// the cut-outs ship as WebP; their PNG sources stay behind for tools/pixelize.js
const SOURCE_ONLY = f => f.startsWith("images/objects/") && f.endsWith(".png");

function list() {
  const files = ["index.html", "manifest.webmanifest"];
  for (const dir of DIRS) {
    for (const f of fs.readdirSync(path.join(ROOT, dir)).sort()) {
      if (!f.startsWith(".") && fs.statSync(path.join(ROOT, dir, f)).isFile() && !SOURCE_ONLY(`${dir}/${f}`)) files.push(`${dir}/${f}`);
    }
  }
  return files;
}

const files = list();
const hash = crypto.createHash("sha256");
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = "pixel-palace-" + hash.digest("hex").slice(0, 12);

// The zoom photos aren't installed up front, but their cache is named after
// their contents, so replacing one gives every device the new file.
const zoomHash = crypto.createHash("sha256");
for (const f of fs.readdirSync(path.join(ROOT, "images/zoom")).sort()) {
  if (f.startsWith(".")) continue;
  zoomHash.update(f).update(fs.readFileSync(path.join(ROOT, "images/zoom", f)));
}
const zoomCache = "pixel-palace-zoom-" + zoomHash.digest("hex").slice(0, 8);

const sw = `// Generated by tools/build-sw.js. Do not edit by hand.
// Caches the whole game on first visit so it keeps working offline,
// for example inside the museum where Wi-Fi is unreliable. The sharp zoom
// photos are large, so each one is kept the first time it's looked at.
const VERSION = ${JSON.stringify(version)};
const ZOOM_CACHE = ${JSON.stringify(zoomCache)};
const FILES = ${JSON.stringify(["./", ...files], null, 2)};

self.addEventListener("install", event => {
  event.waitUntil(caches.open(VERSION).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k.startsWith("pixel-palace-") && k !== VERSION && k !== ZOOM_CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", event => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (url.pathname.includes("/images/zoom/")) {
    event.respondWith(
      caches.open(ZOOM_CACHE).then(cache =>
        cache.match(req).then(hit => hit || fetch(req).then(res => {
          if (res.ok) event.waitUntil(cache.put(req, res.clone()));
          return res;
        }))
      )
    );
    return;
  }
  event.respondWith(
    caches.open(VERSION).then(cache =>
      cache.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).catch(() =>
        req.mode === "navigate" ? cache.match("./index.html") : Response.error()
      ))
    )
  );
});
`;
fs.writeFileSync(path.join(ROOT, "sw.js"), sw);
console.log(`sw.js: ${files.length + 1} files, ${version}`);
